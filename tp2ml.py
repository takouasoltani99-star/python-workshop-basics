import pandas as pd
import matplotlib.pyplot as plt

url = 'https://raw.githubusercontent.com/mwaskom/seaborn-data/master/iris.csv'
iris_df = pd.read_csv(url)

virginica_df = iris_df[iris_df['species'] == 'virginica']
print("First 5 rows of Virginica:\n", virginica_df.head())

min_petal_width = iris_df['petal_width'].min()
max_petal_width = iris_df['petal_width'].max()
print(f"\nPetal Width: Min = {min_petal_width}, Max = {max_petal_width}")

highest_avg_sepal = iris_df.groupby('species')['sepal_length'].mean().idxmax()
print(f"\nSpecies with highest avg sepal length: {highest_avg_sepal}")

iris_df.plot(x='petal_length', y='petal_width', kind='scatter', figsize=(8, 5))
plt.title('Petal Length vs Petal Width')
plt.xlabel('Petal Length (cm)')
plt.ylabel('Petal Width (cm)')
plt.show()
iris_df.groupby('species')['petal_length'].mean().plot(kind='bar', figsize=(8, 5), color='green')
plt.title('Average Petal Length by Species')
plt.xlabel('Species')
plt.ylabel('Average Petal Length (cm)')
plt.xticks(rotation=0)
plt.show()