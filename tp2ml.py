import pandas as pd

sales_data = {
    'Product': ['A', 'B', 'A', 'C', 'B', 'C', 'A', 'B'],
    'Region': ['North', 'South', 'East', 'West', 'North', 'South', 'West', 'East'],
    'Sales': [150, 200, 300, 400, 250, 100, 180, 310]
}
df_sales = pd.DataFrame(sales_data)
total_sales_by_product = df_sales.groupby('Product')['Sales'].sum()
print("Total Sales by Product:\n", total_sales_by_product)
avg_sales_by_region = df_sales.groupby('Region')['Sales'].mean()
print("\nAverage Sales by Region:\n", avg_sales_by_region)
agg_product_sales = df_sales.groupby('Product')['Sales'].agg(['mean', 'max'])
print("\nMean and Max Sales by Product:\n", agg_product_sales)

